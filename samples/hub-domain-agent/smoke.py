"""Two text invocations of an existing deployed role, preserving versions and cleaning owned sessions."""

from __future__ import annotations

import argparse
import asyncio
import hashlib
import json
import uuid
from pathlib import Path
from typing import Any

import httpx
from azure.identity.aio import DefaultAzureCredential

from common.config import project_endpoint
from common.protocol import AI_SCOPE, sse_events


def manifest(path: Path) -> dict[str, Any]:
    value = json.loads(path.read_text())
    project_endpoint(value["project_endpoint"])
    if set(value["agents"]) != {"hub", "billing", "booking"}:
        raise ValueError("Use the complete deployment.json generated by deploy.py")
    return value


def agent_base(deployment: dict[str, Any], role: str) -> str:
    return deployment["project_endpoint"] + "/agents/" + deployment["agents"][role]["name"] + "/endpoint"


async def auth(credential: Any) -> dict[str, str]:
    token = await credential.get_token(AI_SCOPE)
    return {
        "Authorization": "Bearer " + token.token,
        "Foundry-Features": "HostedAgents=V1Preview",
        "x-ms-debug-latency-enabled": "true",
    }


async def action(
    http: httpx.AsyncClient, deployment: dict[str, Any], role: str, sid: str, headers: dict[str, str], name: str
) -> dict[str, Any]:
    response = await http.post(
        agent_base(deployment, role) + "/protocols/invocations",
        params={"api-version": "v1", "agent_session_id": sid},
        headers=headers,
        json={"action": name},
    )
    response.raise_for_status()
    return response.json()


async def cleanup(
    http: httpx.AsyncClient, deployment: dict[str, Any], role: str, sid: str, headers: dict[str, str]
) -> None:
    """Check/delete only this run's exact parent and deterministic child IDs."""
    owned = [(role, sid)]
    if role == "hub":
        owned = [
            (child, child + "_" + hashlib.sha256(sid.encode()).hexdigest()[:40]) for child in ("billing", "booking")
        ] + owned
    errors = []
    for owner, exact_id in owned:
        path = agent_base(deployment, owner) + "/sessions/" + exact_id
        try:
            resource = await http.get(path, params={"api-version": "v1"}, headers=headers)
            if resource.status_code == 404:
                continue
            resource.raise_for_status()
            if resource.json()["version_indicator"]["agent_version"] != deployment["agents"][owner]["version"]:
                raise RuntimeError("Refusing to delete owned ID with unexpected version")
            response = await http.delete(path, params={"api-version": "v1"}, headers=headers)
            if response.status_code != 404:
                response.raise_for_status()
            check = await http.get(path, params={"api-version": "v1"}, headers=headers)
            if check.status_code != 404:
                check.raise_for_status()
                raise RuntimeError("Owned session remains after deletion")
        except Exception as error:
            errors.append(error)
    if errors:
        raise ExceptionGroup("Cleanup incomplete; keep the exact owned IDs for operator cleanup", errors)


async def run(deployment: dict[str, Any], role: str, inputs: list[str], output: Path) -> None:
    if output.exists():
        raise FileExistsError("Choose a fresh result path; do not overwrite a previous test")
    sid = "sample-" + uuid.uuid4().hex
    report: dict[str, Any] = {"role": role, "session_id": sid, "turns": [], "cleanup_complete": False}
    output.parent.mkdir(parents=True, exist_ok=True)
    async with DefaultAzureCredential() as credential, httpx.AsyncClient(timeout=90) as http:
        headers = await auth(credential)
        try:
            response = await http.post(
                agent_base(deployment, role) + "/sessions",
                params={"api-version": "v1"},
                headers=headers,
                json={
                    "agent_session_id": sid,
                    "version_indicator": {
                        "type": "version_ref",
                        "agent_version": deployment["agents"][role]["version"],
                    },
                },
            )
            response.raise_for_status()
            for text in inputs:
                answer, done = "", False
                async with http.stream(
                    "POST",
                    agent_base(deployment, role) + "/protocols/invocations",
                    params={"api-version": "v1", "agent_session_id": sid},
                    headers=headers,
                    json={"input": text},
                ) as response:
                    response.raise_for_status()
                    async for event in sse_events(response.aiter_lines()):
                        if event.get("type") == "error":
                            raise RuntimeError("Agent returned an error; no retry or replacement")
                        if event.get("type") == "output_audio_transcription.delta":
                            answer += event["delta"]
                        if event.get("type") == "done":
                            done = True
                if not answer or not done:
                    raise RuntimeError("Response incomplete or empty")
                status = await action(http, deployment, role, sid, headers, "status")
                if not status["captured"] or not status["restore_id"]:
                    raise RuntimeError("Memory snapshot restoration was not observed")
                report["turns"].append({"answer": answer, "status": status})
                print(answer)
        finally:
            try:
                await cleanup(http, deployment, role, sid, await auth(credential))
                report["cleanup_complete"] = True
            finally:
                output.write_text(json.dumps(report, indent=2) + "\n")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--deployment", type=Path, default=Path("deployment.json"))
    parser.add_argument("--role", choices=("hub", "billing", "booking"), default="hub")
    parser.add_argument("--turn1", default="Why did my bill increase by thirty yuan this month?")
    parser.add_argument("--turn2", default="How were those extra thirty yuan calculated?")
    parser.add_argument("--output", type=Path, default=Path("results/smoke.json"))
    args = parser.parse_args()
    asyncio.run(run(manifest(args.deployment), args.role, [args.turn1, args.turn2], args.output))


if __name__ == "__main__":
    main()
